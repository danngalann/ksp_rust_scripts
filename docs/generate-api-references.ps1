[CmdletBinding()]
param(
    [string]$ServicesPath,
    [string]$OutputDirectory
)

$ErrorActionPreference = 'Stop'

if ([string]::IsNullOrWhiteSpace($ServicesPath)) {
    $ServicesPath = Join-Path $PSScriptRoot '..\services'
}

if ([string]::IsNullOrWhiteSpace($OutputDirectory)) {
    $OutputDirectory = Join-Path $PSScriptRoot 'api'
}

function Get-Properties([object]$Value) {
    if ($null -eq $Value) {
        return @()
    }

    return @($Value.PSObject.Properties)
}

function Get-Slug([string]$Name) {
    return (($Name -creplace '([a-z0-9])([A-Z])', '$1-$2').ToLowerInvariant())
}

function Format-Type([object]$Type) {
    if ($null -eq $Type) {
        return 'void'
    }

    $innerTypes = @($Type.types | ForEach-Object { Format-Type $_ })
    switch ($Type.code) {
        'LIST' { return "List<$($innerTypes -join ', ')>" }
        'SET' { return "Set<$($innerTypes -join ', ')>" }
        'DICTIONARY' { return "Dictionary<$($innerTypes -join ', ')>" }
        'TUPLE' { return "($($innerTypes -join ', '))" }
        'CLASS' { return $Type.name }
        'ENUMERATION' { return $Type.name }
        default { return $Type.code }
    }
}

function Format-Documentation([string]$Documentation) {
    if ([string]::IsNullOrWhiteSpace($Documentation)) {
        return ''
    }

    $text = $Documentation -replace '<[^>]+>', ' '
    $text = [System.Net.WebUtility]::HtmlDecode($text)
    return ($text -replace '\s+', ' ').Trim()
}

function Format-Parameters([object[]]$Parameters) {
    $Parameters = @($Parameters | Where-Object { $_.name -ne 'this' })
    if ($Parameters.Count -eq 0) {
        return 'None'
    }

    return ($Parameters | ForEach-Object {
        $default = if ($null -ne $_.default_value) { ' (optional)' } else { '' }
        "``$($_.name): $(Format-Type $_.type)``$default"
    }) -join ', '
}

function Add-ProcedureTable(
    [System.Collections.Generic.List[string]]$Lines,
    [object[]]$Procedures
) {
    if ($Procedures.Count -eq 0) {
        $Lines.Add('No callable members.')
        $Lines.Add('')
        return
    }

    $Lines.Add('| RPC member | Parameters | Returns | Scenes | Description |')
    $Lines.Add('| --- | --- | --- | --- | --- |')
    foreach ($procedure in $Procedures) {
        $definition = $procedure.Value
        $parameters = Format-Parameters @($definition.parameters)
        $returnType = Format-Type $definition.return_type
        $scenes = if ($definition.game_scenes) { @($definition.game_scenes) -join ', ' } else { 'Any' }
        $summary = (Format-Documentation $definition.documentation) -replace '\|', '\|'
        $Lines.Add("| ``$($procedure.Name)`` | $parameters | ``$returnType`` | $scenes | $summary |")
    }
    $Lines.Add('')
}

function Write-ServiceReference(
    [string]$ServiceName,
    [object]$Service,
    [string]$Path,
    [string]$GeneratedAt
) {
    $lines = [System.Collections.Generic.List[string]]::new()
    $allProcedures = @(Get-Properties $Service.procedures)
    $classNames = @(Get-Properties $Service.classes | ForEach-Object Name)

    $lines.Add("# $ServiceName API Reference")
    $lines.Add('')
    $lines.Add("Generated on $GeneratedAt from ``services/KRPC.$ServiceName.json``. Do not edit this file by hand; run ``powershell -ExecutionPolicy Bypass -File docs\generate-api-references.ps1`` after changing a service schema.")
    $lines.Add('')
    $lines.Add('This is the API surface available to this project, not a substitute for the official kRPC documentation. Calls are grouped by their owning class. The names below are the original schema RPC names; generated Rust method names are usually their lowercase snake-case equivalents. Each call must be sent through `krpc_mars::RPCClient::mk_call`.')
    $lines.Add('')
    $lines.Add('## Service procedures')
    $lines.Add('')

    $serviceProcedures = @(
        $allProcedures | Where-Object {
            $procedureName = $_.Name
            -not ($classNames | Where-Object { $procedureName.StartsWith("$_`_") })
        } | Sort-Object Name
    )
    Add-ProcedureTable $lines $serviceProcedures

    $lines.Add('## Classes')
    $lines.Add('')

    foreach ($class in (Get-Properties $Service.classes | Sort-Object Name)) {
        $definition = $class.Value
        $lines.Add("### ``$($class.Name)``")
        $lines.Add('')
        $summary = Format-Documentation $definition.documentation
        if ($summary) {
            $lines.Add($summary)
            $lines.Add('')
        }

        $members = @(
            $allProcedures | Where-Object { $_.Name.StartsWith("$($class.Name)_") } | Sort-Object Name
        )
        Add-ProcedureTable $lines $members
    }

    $lines.Add('## Enumerations')
    $lines.Add('')
    foreach ($enumeration in (Get-Properties $Service.enumerations | Sort-Object Name)) {
        $lines.Add("### ``$($enumeration.Name)``")
        $lines.Add('')
        $summary = Format-Documentation $enumeration.Value.documentation
        if ($summary) {
            $lines.Add($summary)
            $lines.Add('')
        }
        $lines.Add('| Value | Numeric value |')
        $lines.Add('| --- | --- |')
        foreach ($value in @($enumeration.Value.values)) {
            $lines.Add("| ``$($value.name)`` | $($value.value) |")
        }
        $lines.Add('')
    }

    $utf8WithoutBom = [System.Text.UTF8Encoding]::new($false)
    [System.IO.File]::WriteAllLines($Path, $lines, $utf8WithoutBom)
}

New-Item -ItemType Directory -Force -Path $OutputDirectory | Out-Null
Get-ChildItem -Path $OutputDirectory -File -Filter '*.md' |
    Where-Object { $_.Name -ne 'README.md' } |
    ForEach-Object { Remove-Item -LiteralPath $_.FullName }

$generatedAt = Get-Date -Format 'yyyy-MM-dd'
Get-ChildItem -Path $ServicesPath -File -Filter 'KRPC.*.json' |
    Sort-Object Name |
    ForEach-Object {
        $schema = Get-Content -Raw -Encoding utf8 $_.FullName | ConvertFrom-Json
        $serviceProperty = @(Get-Properties $schema)
        if ($serviceProperty.Count -ne 1) {
            throw "Expected exactly one service in $($_.FullName)."
        }

        $serviceName = $serviceProperty[0].Name
        $outputPath = Join-Path $OutputDirectory "$(Get-Slug $serviceName).md"
        Write-ServiceReference $serviceName $serviceProperty[0].Value $outputPath $generatedAt
    }
